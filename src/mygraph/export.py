"""Turn the graph into the formats other tools speak.

    graph.json   what the visualisation reads
    web json     the same, trimmed for a phone
    Cypher       load the same graph into Neo4j or Memgraph
    GraphML      open it in Gephi, yEd or Cytoscape
    Mermaid      drop a diagram into a README
    HTML         one self-contained file, data included
"""

from __future__ import annotations

import json
import pathlib
import re
from typing import Any

import yaml

from .metrics import all_metrics
from .model import Graph

DATA_MARKER = "/*__GRAPH_DATA__*/null"


def to_dict(graph: Graph, root: pathlib.Path | str = ".") -> dict[str, Any]:
    root = pathlib.Path(root)
    palette_path = root / "schema" / "palette.yaml"
    palette = yaml.safe_load(palette_path.read_text(encoding="utf-8")) if palette_path.exists() else {}
    metrics = all_metrics(graph)
    ontology = graph.ontology

    return {
        "meta": {
            **ontology.meta,
            "subject": ontology.subject,
            "stage_count": ontology.stage_count,
            "node_count": len(graph.nodes),
            "edge_count": len(graph.edges),
        },
        "palette": palette,
        "node_types": [
            {
                "name": t.name,
                "label": t.label,
                "plural": t.plural,
                "stage": t.stage,
                "glyph": t.glyph,
                "palette": t.palette,
                "question": t.question,
                "count": len(graph.by_type(t.name)),
            }
            for t in sorted(ontology.node_types.values(), key=lambda t: t.stage)
        ],
        "edge_types": [
            {"name": t.name, "label": t.label, "kind": t.kind}
            for t in ontology.edge_types.values()
        ],
        "sources": ontology.sources,
        "nodes": [
            {**node.as_row(), "stage": ontology.stage_of(node.type), **metrics[node.id]}
            for node in graph.nodes
        ],
        "edges": [
            {**edge.as_row(), "kind": ontology.edge_types[edge.rel].kind,
             "rel_label": ontology.edge_types[edge.rel].label}
            for edge in graph.edges
        ],
    }


def write_json(graph: Graph, path: pathlib.Path | str, root: pathlib.Path | str = ".") -> pathlib.Path:
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(to_dict(graph, root), indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8")
    return path


def to_web(graph: Graph, root: pathlib.Path | str = ".") -> dict[str, Any]:
    """The same graph, trimmed for a phone.

    Drops the measures a reader never sees, rounds the ones they do, and strips
    the bookkeeping fields. Roughly a fifth smaller over the wire, which is a
    fifth less to pull down on a mobile connection.
    """
    full = to_dict(graph, root)
    drop_node = {"betweenness", "in_degree", "out_degree", "origin"}
    nodes = []
    for node in full["nodes"]:
        slim = {k: v for k, v in node.items() if k not in drop_node}
        slim["pagerank"] = round(float(slim["pagerank"]), 5)
        slim["degree"] = round(float(slim["degree"]), 2)
        slim["stage"] = int(slim["stage"])
        slim["audiences_reached"] = int(slim["audiences_reached"])
        slim["outcomes_produced"] = int(slim["outcomes_produced"])
        if not slim.get("refs"):
            slim.pop("refs", None)
        if not slim.get("props"):
            slim.pop("props", None)
        if not slim.get("subtitle"):
            slim.pop("subtitle", None)
        nodes.append(slim)
    edges = []
    for edge in full["edges"]:
        slim = {k: v for k, v in edge.items() if k not in {"id", "confidence"}}
        slim["weight"] = round(float(slim["weight"]), 2)
        if not slim.get("note"):
            slim.pop("note", None)
        edges.append(slim)
    return {**full, "nodes": nodes, "edges": edges}


def write_web_json(
    graph: Graph, path: pathlib.Path | str, root: pathlib.Path | str = "."
) -> pathlib.Path:
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(to_web(graph, root), ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    return path


def to_cypher(graph: Graph) -> str:
    """A Cypher script that rebuilds the graph in Neo4j or Memgraph."""
    lines = [
        "// mygraph — generated by `mygraph export cypher`. Do not edit by hand.",
        "// Run against an empty database.",
        "",
    ]
    for node_type in sorted(graph.ontology.node_types):
        label = _pascal(node_type)
        lines.append(f"CREATE CONSTRAINT IF NOT EXISTS FOR (n:{label}) REQUIRE n.id IS UNIQUE;")
    lines.append("")

    for node in graph.nodes:
        props = {
            "id": node.id,
            "label": node.label,
            "subtitle": node.subtitle,
            "summary": " ".join(node.summary.split()),
            "source": node.source,
            "confidence": node.confidence,
            "stage": graph.ontology.stage_of(node.type),
        }
        for key, value in node.props.items():
            props[f"prop_{_snake(key)}"] = value
        if node.refs:
            props["refs"] = list(node.refs)
        lines.append(f"CREATE (:{_pascal(node.type)} {_cypher_map(props)});")
    lines.append("")

    for edge in graph.edges:
        rel = edge.rel.upper()
        props = {
            "weight": edge.weight,
            "source": edge.source,
            "confidence": edge.confidence,
            "kind": graph.ontology.edge_types[edge.rel].kind,
        }
        if edge.note:
            props["note"] = " ".join(edge.note.split())
        lines.append(
            f"MATCH (a {{id: {_cypher_value(edge.src)}}}), (b {{id: {_cypher_value(edge.dst)}}})"
            f" CREATE (a)-[:{rel} {_cypher_map(props)}]->(b);"
        )
    return "\n".join(lines) + "\n"


def to_graphml(graph: Graph) -> str:
    """GraphML for Gephi, yEd and Cytoscape."""
    metrics = all_metrics(graph)
    keys = [
        ("label", "node", "string"), ("ntype", "node", "string"),
        ("stage", "node", "int"), ("pagerank", "node", "double"),
        ("source", "node", "string"), ("summary", "node", "string"),
        ("rel", "edge", "string"), ("weight", "edge", "double"),
        ("kind", "edge", "string"),
    ]
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<graphml xmlns="http://graphml.graphdrawing.org/xmlns">']
    for name, domain, kind in keys:
        out.append(f'  <key id="{name}" for="{domain}" attr.name="{name}" attr.type="{kind}"/>')
    out.append('  <graph id="mygraph" edgedefault="directed">')
    for node in graph.nodes:
        out.append(f'    <node id="{_xml(node.id)}">')
        out.append(f'      <data key="label">{_xml(node.label)}</data>')
        out.append(f'      <data key="ntype">{_xml(node.type)}</data>')
        out.append(f'      <data key="stage">{graph.ontology.stage_of(node.type)}</data>')
        out.append(f'      <data key="pagerank">{metrics[node.id]["pagerank"]:.6f}</data>')
        out.append(f'      <data key="source">{_xml(node.source)}</data>')
        out.append(f'      <data key="summary">{_xml(" ".join(node.summary.split()))}</data>')
        out.append("    </node>")
    for edge in graph.edges:
        out.append(f'    <edge source="{_xml(edge.src)}" target="{_xml(edge.dst)}">')
        out.append(f'      <data key="rel">{_xml(edge.rel)}</data>')
        out.append(f'      <data key="weight">{edge.weight}</data>')
        out.append(f'      <data key="kind">{_xml(graph.ontology.edge_types[edge.rel].kind)}</data>')
        out.append("    </edge>")
    out += ["  </graph>", "</graphml>"]
    return "\n".join(out) + "\n"


def to_mermaid(graph: Graph, include: tuple[str, ...] = ("person", "practice", "audience", "outcome")) -> str:
    """A small Mermaid flowchart. The full graph is too dense to read this way."""
    keep = {n.id for n in graph.nodes if n.type in include}
    lines = ["flowchart LR"]
    for node_type in include:
        members = [n for n in graph.nodes if n.type == node_type]
        if not members:
            continue
        lines.append(f"  subgraph {node_type}[{graph.ontology.node_types[node_type].plural}]")
        for node in members:
            lines.append(f'    {_mid(node.id)}["{node.label}"]')
        lines.append("  end")
    for edge in graph.edges:
        if edge.src in keep and edge.dst in keep:
            arrow = "-.->" if graph.ontology.edge_types[edge.rel].kind == "return" else "-->"
            lines.append(f"  {_mid(edge.src)} {arrow}|{edge.rel.replace('_', ' ')}| {_mid(edge.dst)}")
    return "\n".join(lines) + "\n"


def write_single_file_html(
    graph: Graph, template: pathlib.Path | str, path: pathlib.Path | str,
    root: pathlib.Path | str = ".",
) -> pathlib.Path:
    """Inline the data into the page template, giving one file that needs nothing."""
    template = pathlib.Path(template)
    path = pathlib.Path(path)
    html = template.read_text(encoding="utf-8")
    if DATA_MARKER not in html:
        raise ValueError(f"{template}: the data marker {DATA_MARKER} is missing")
    payload = json.dumps(to_dict(graph, root), ensure_ascii=False, separators=(",", ":"))
    payload = payload.replace("</", "<\\/")  # never close the script tag early
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(html.replace(DATA_MARKER, payload), encoding="utf-8")
    return path


# ------------------------------------------------------------------- helpers
def _pascal(name: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[-_]", name) if part)


def _snake(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def _mid(node_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", node_id)


def _cypher_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_cypher_value(v) for v in value) + "]"
    text = str(value).replace("\\", "\\\\").replace("'", "\\'").replace("\n", " ")
    return f"'{text}'"


def _cypher_map(props: dict[str, Any]) -> str:
    inner = ", ".join(f"{key}: {_cypher_value(value)}" for key, value in props.items() if value != "")
    return "{" + inner + "}"


def _xml(text: Any) -> str:
    return (
        str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace('"', "&quot;")
    )
